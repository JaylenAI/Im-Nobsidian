import type { BasePropertySchema, DatabaseViewsConfig, ViewConfig } from "../types/view.js";
import { translateNotionFilter, type BasesFilterNode } from "./notion-filter-translator.js";
import { resolvePropertyName } from "./property-resolver.js";

export interface BaseFileOptions {
  readonly databaseId: string;
  readonly databaseName: string;
  readonly schema: Record<string, BasePropertySchema>;
  readonly viewsConfig: DatabaseViewsConfig;
  readonly folderPath: string;
}

export type BasesViewType = "table" | "cards" | "list";

/** Notion 뷰 하나를 Bases 로 옮길 때의 판정. */
export interface BasesViewMapping {
  /** Bases 뷰 타입. `null` = 대응이 없어 `.base` 에 실을 수 없음. */
  readonly type: BasesViewType | null;
  /**
   * 값이 있으면 **정확한 대응이 아니라 격하**라는 뜻(사람용 사유).
   * 뷰 자체는 살아남지만 원래 뷰의 표현 일부(달력 격자·타임라인 축)는 재현되지 않는다.
   */
  readonly degradeReason?: string;
}

/**
 * Notion 뷰 타입 → Obsidian Bases 뷰 매핑(SSOT).
 *
 * 뷰는 현재 pull-authoritative — Notion API 가 2026-03-19 뷰 생성/수정/삭제를 열었지만
 * 본 프로젝트는 아직 뷰 write-back 을 구현하지 않았다(로드맵 항목). push 로 되돌릴 수
 * 없는 동안 "조용한 유실 금지"는 곧 "보존 + 정직한 degrade 리포트"를 의미한다.
 *
 * 달력·타임라인은 예전에 `null` 이었다 — 즉 `.base` 에서 **통째로 사라졌다**. 사이드카에는
 * 남지만 Obsidian 을 여는 사람 눈에는 그 뷰가 애초에 없었던 것처럼 보인다. 격자·축은
 * 못 살려도 "날짜 순으로 늘어놓은 목록"이라는 본래 의도는 표로 남길 수 있으므로,
 * 버리는 대신 격하해 살리고 사유를 사이드카에 적는다.
 */
export const NOTION_TO_BASES_VIEW: Record<string, BasesViewMapping> = {
  table: { type: "table" },
  gallery: { type: "cards" },
  list: { type: "list" },
  board: { type: "cards" },
  calendar: {
    type: "table",
    degradeReason: "달력 격자는 Bases 미지원 — 날짜 오름차순 표로 격하",
  },
  timeline: {
    type: "table",
    degradeReason: "타임라인 축은 Bases 미지원 — 날짜 오름차순 표로 격하",
  },
  form: { type: null },
  chart: { type: null },
  map: { type: null },
  dashboard: { type: null },
};

/** Notion 뷰 타입의 Bases 매핑. 미상 타입은 표현 불가로 본다. */
export function basesViewMappingOf(notionType: string): BasesViewMapping {
  return NOTION_TO_BASES_VIEW[notionType] ?? { type: null };
}

/** Notion 뷰 타입의 Bases 대응 타입을 돌려준다. 미지원/미상 타입은 `null`. */
export function basesViewTypeOf(notionType: string): BasesViewType | null {
  return basesViewMappingOf(notionType).type;
}

/** `.base` 의 `views[]` 한 항목. 이름은 dedupe 로 바뀔 수 있어 가변으로 둔다. */
interface BasesView {
  type: BasesViewType;
  name: string;
  order?: string[];
  sort?: Array<{ property: string; direction: string }>;
  groupBy?: { property: string; direction?: string };
  image?: string;
  filters?: BasesFilterNode;
}

/** 필터 그룹 노드에서 `[연산자, 자식들]` 을 꺼낸다. */
function filterGroup(
  node: Exclude<BasesFilterNode, string>,
): ["and" | "or" | "not", BasesFilterNode[]] {
  if ("and" in node) return ["and", node.and];
  if ("or" in node) return ["or", node.or];
  return ["not", node.not];
}

export class BaseFileGenerator {
  generate(options: BaseFileOptions): string {
    const lines: string[] = [];

    lines.push(`# Auto-generated by Im-Nobsidian from Notion DB: ${options.databaseName}`);
    lines.push(`# Database ID: ${options.databaseId}`);
    lines.push("");

    this.writeFilters(lines, options.folderPath);
    this.writeFormulas(lines, options.viewsConfig.views);
    this.writePropertyDisplayNames(lines, options.schema);
    this.writeViews(lines, options.viewsConfig.views, options.schema);

    // YAML 파일은 말미 개행으로 끝낸다(POSIX 텍스트 관례·diff 안정성).
    return lines.join("\n") + "\n";
  }

  private writeFilters(lines: string[], folderPath: string): void {
    lines.push("filters:");
    lines.push("  and:");
    lines.push(`    - file.inFolder("${folderPath}")`);
    // `.base` 파일 자신도 폴더에 있어 카드로 잡히므로(빈 카드) markdown 노트만 남긴다.
    lines.push(`    - file.ext == "md"`);
    lines.push("");
  }

  private needsContentCoverFormula(views: ViewConfig[]): boolean {
    return views.some(
      (v) =>
        v.type === "gallery" &&
        v.cover &&
        (v.cover.type === "page_content" || v.cover.type === "page_content_first"),
    );
  }

  private writeFormulas(lines: string[], views: ViewConfig[]): void {
    if (!this.needsContentCoverFormula(views)) return;

    lines.push("formulas:");
    lines.push("  coverImage: file.embeds[0]");
    lines.push("");
  }

  private writePropertyDisplayNames(
    lines: string[],
    schema: Record<string, BasePropertySchema>,
  ): void {
    const entries = Object.entries(schema).filter(([, prop]) => prop.type !== "title");
    if (entries.length === 0) return;

    lines.push("properties:");
    for (const [name] of entries) {
      lines.push(`  ${this.yamlKey(name)}:`);
      lines.push(`    displayName: ${this.yamlValue(name)}`);
    }
    lines.push("");
  }

  private writeViews(
    lines: string[],
    views: ViewConfig[],
    schema: Record<string, BasePropertySchema>,
  ): void {
    const basesViews = views
      .map((v) => this.convertView(v, schema))
      .filter((v): v is NonNullable<typeof v> => v !== null);

    if (basesViews.length === 0) {
      lines.push("views:");
      lines.push("  - type: table");
      lines.push("    name: Table");
      return;
    }

    // Obsidian Bases 는 뷰 이름 유일성을 요구한다. Notion 은 이름 없는 뷰를 'Untitled'로
    // 반환하므로(동명 다수 발생) 중복 시 ' 2','3'… 접미사로 유일화한다. 미적용 시 Bases 가
    // 동명 뷰를 하나로 합치거나 무시해 갤러리·표 뷰가 사라진다.
    this.dedupeViewNames(basesViews);

    lines.push("views:");
    for (const view of basesViews) {
      lines.push(`  - type: ${view.type}`);
      lines.push(`    name: ${this.yamlValue(view.name)}`);

      if (view.order && view.order.length > 0) {
        lines.push("    order:");
        for (const col of view.order) {
          lines.push(`      - ${this.propRef(col)}`);
        }
      }

      if (view.sort && view.sort.length > 0) {
        lines.push("    sort:");
        for (const s of view.sort) {
          // Bases 정렬 항목의 키는 `property`다(`column` 아님 — Obsidian이 무시함).
          lines.push(`      - property: ${this.propRef(s.property)}`);
          lines.push(`        direction: ${s.direction}`);
        }
      }

      if (view.groupBy) {
        lines.push("    groupBy:");
        lines.push(`      property: ${this.propRef(view.groupBy.property)}`);
        if (view.groupBy.direction) {
          lines.push(`      direction: ${view.groupBy.direction}`);
        }
      }

      if (view.image) {
        lines.push(`    image: ${this.propRef(view.image)}`);
      }

      // 뷰별 필터는 전역 `filters:` 와 AND 로 결합된다(폴더/확장자 제한은 그대로 유지).
      if (view.filters) {
        this.writeFilterValue(lines, view.filters, "    ");
      }
    }
  }

  /** `filters:` 키와 그 값을 쓴다. 단일 식이면 한 줄, 그룹이면 블록. */
  private writeFilterValue(lines: string[], node: BasesFilterNode, indent: string): void {
    if (typeof node === "string") {
      lines.push(`${indent}filters: ${this.yamlExpr(node)}`);
      return;
    }
    lines.push(`${indent}filters:`);
    const [op, children] = filterGroup(node);
    lines.push(`${indent}  ${op}:`);
    for (const child of children) {
      this.writeFilterItem(lines, child, `${indent}    `);
    }
  }

  /** 필터 노드를 시퀀스 항목(`- …`)으로 쓴다. 그룹이면 재귀적으로 중첩한다. */
  private writeFilterItem(lines: string[], node: BasesFilterNode, indent: string): void {
    if (typeof node === "string") {
      lines.push(`${indent}- ${this.yamlExpr(node)}`);
      return;
    }
    const [op, children] = filterGroup(node);
    lines.push(`${indent}- ${op}:`);
    for (const child of children) {
      this.writeFilterItem(lines, child, `${indent}    `);
    }
  }

  /**
   * 필터 식을 YAML 스칼라로 쓴다.
   *
   * 식은 대개 `note["상태"] == "진행 중"` 처럼 큰따옴표를 품는다. 평문 스칼라는 큰따옴표를
   * 안에 담을 수 있으므로(선두만 아니면 된다) 기본은 평문으로 두어 기존 `file.ext == "md"`
   * 라인과 모양을 맞춘다. 다만 `: `·` #`·선두 지시문자는 평문에서 의미가 달라지므로
   * 그때만 작은따옴표로 감싼다(속성명에 콜론이나 해시가 들어갈 수 있다).
   */
  private yamlExpr(expr: string): string {
    const unsafe =
      expr !== expr.trim() ||
      expr.includes(": ") ||
      expr.includes(" #") ||
      expr.endsWith(":") ||
      /^[-?:,[\]{}#&*!|>'"%@`]/.test(expr);
    if (!unsafe) return expr;
    return `'${expr.replace(/'/g, "''")}'`;
  }

  /**
   * 뷰 이름을 Bases 요구사항대로 유일화한다(in-place). 동명 충돌 시 ' 2',' 3'… 를 붙이되
   * 이미 존재하는 이름과 다시 충돌하지 않을 때까지 증가시킨다.
   */
  private dedupeViewNames(views: Array<{ name: string }>): void {
    const used = new Set<string>();
    for (const v of views) {
      let name = v.name;
      if (used.has(name)) {
        let n = 2;
        while (used.has(`${v.name} ${n}`)) n++;
        name = `${v.name} ${n}`;
      }
      used.add(name);
      v.name = name;
    }
  }

  private convertView(
    view: ViewConfig,
    schema: Record<string, BasePropertySchema>,
  ): BasesView | null {
    const basesType = basesViewMappingOf(view.type).type;
    if (!basesType) return null;

    const result: BasesView = {
      type: basesType,
      name: view.name || view.type,
    };

    if (view.properties && view.properties.length > 0) {
      const visible = view.properties
        .filter((p) => p.visible !== false)
        .map((p) => {
          const name = p.propertyName ?? this.resolvePropertyName(p.propertyId, schema);
          if (!name) return null;
          // title 타입 속성은 카드/표 제목(file.name)과 중복되고, 프론트매터엔
          // title 키가 없어(본문 H1·파일명으로 보존) 빈 컬럼으로 표시되므로 제외한다.
          if (schema[name]?.type === "title") return null;
          return this.toNoteRef(name);
        })
        .filter((name): name is string => !!name);

      if (visible.length > 0) {
        result.order = ["file.name", ...visible];
      }
    }

    if (view.sorts && view.sorts.length > 0) {
      result.sort = view.sorts
        .map((s) => {
          let property: string;
          if (s.property) {
            const propName = this.resolvePropertyName(s.property, schema) ?? s.property;
            property = this.toNoteRef(propName);
          } else if (s.timestamp) {
            property = s.timestamp === "created_time" ? "file.ctime" : "file.mtime";
          } else {
            return null;
          }
          return {
            property,
            direction: s.direction === "ascending" ? "ASC" : "DESC",
          };
        })
        .filter((s): s is NonNullable<typeof s> => s !== null);
    }

    if (view.groupBy) {
      const propName =
        view.groupBy.propertyName ?? this.resolvePropertyName(view.groupBy.propertyId, schema);
      if (propName) {
        result.groupBy = {
          property: this.toNoteRef(propName),
          direction:
            view.groupBy.sort === "ascending"
              ? "ASC"
              : view.groupBy.sort === "descending"
                ? "DESC"
                : undefined,
        };
      }
    }

    // 달력/타임라인은 격자·축을 못 살린다. 그래도 "시간 순서"라는 본래 의도는 남길 수
    // 있으므로, 명시 정렬이 없으면 날짜 속성 오름차순을 넣어 표로 격하한다.
    if ((view.type === "calendar" || view.type === "timeline") && !result.sort?.length) {
      const dateName =
        view.datePropertyName ??
        (view.datePropertyId ? this.resolvePropertyName(view.datePropertyId, schema) : undefined);
      if (dateName) {
        result.sort = [{ property: this.toNoteRef(dateName), direction: "ASC" }];
      }
    }

    if (view.type === "gallery" && view.cover) {
      if (view.cover.type === "property" && view.cover.propertyId) {
        const propName = this.resolvePropertyName(view.cover.propertyId, schema);
        if (propName) result.image = this.toNoteRef(propName);
      } else if (view.cover.type === "page_cover") {
        result.image = "note.cover";
      } else if (view.cover.type === "page_content" || view.cover.type === "page_content_first") {
        result.image = "formula.coverImage";
      }
    }

    // Notion 뷰 필터를 Bases 식으로 옮긴다. 옮기지 못한 조건은 여기서 조용히 빠지지만,
    // 사이드카가 같은 번역기를 돌려 무엇이 빠졌는지 degrade 리포트에 남긴다.
    if (view.filter !== undefined && view.filter !== null) {
      const { node } = translateNotionFilter(view.filter, schema, (id) =>
        this.resolvePropertyName(id, schema),
      );
      if (node) result.filters = node;
    }

    return result;
  }

  private toNoteRef(propertyName: string): string {
    return propertyName;
  }

  /**
   * 속성 참조(order/sort/groupBy/image)를 YAML로 안전하게 출력한다.
   * `file.name`·`formula.coverImage`·`note.cover` 같은 접두사 식별자와 공백 포함 일반 속성명은
   * 평문 스칼라로 안전하므로 그대로 두고, 콜론·해시·따옴표 등 YAML 메타문자가 있을 때만 인용한다.
   */
  private propRef(ref: string): string {
    if (/^[A-Za-z0-9_][A-Za-z0-9_. ]*$/.test(ref) && !ref.endsWith(" ")) return ref;
    return `"${ref.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
  }

  private resolvePropertyName(
    propertyId: string,
    schema: Record<string, BasePropertySchema>,
  ): string | undefined {
    return resolvePropertyName(propertyId, schema);
  }

  private yamlKey(key: string): string {
    if (/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(key)) return key;
    return `"${key.replace(/"/g, '\\"')}"`;
  }

  private yamlValue(value: string): string {
    if (/^[a-zA-Z0-9_-]+$/.test(value)) return value;
    return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
  }
}
